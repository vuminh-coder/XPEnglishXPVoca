/**
 * Check if payload is a Google Bot Throttling HTML page ("We're sorry...")
 */
export function isGoogleRateLimitHtml(text: string): boolean {
  if (!text) return true;
  const lower = text.toLowerCase();
  return (
    lower.includes("we're sorry") ||
    lower.includes("<title>sorry...") ||
    lower.includes("automated queries") ||
    (lower.startsWith("<!doctype html") && !lower.includes("<text"))
  );
}

