/**
 * Fetch all available caption tracks via YouTube Innertube API + Watch Page HTML + External Proxy Fallback
 */
export async function fetchInnertubeCaptionTracks(videoId: string): Promise<{
  tracks: CaptionTrackInfo[];
  translationLanguages: TranslationLanguageInfo[];
  videoTitle?: string;
}> {
  const reqHeaders = {
    "User-Agent":
      "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36",
    "Accept-Language": "en-US,en;q=0.9,vi;q=0.8",
  };

  // Helper to parse captionTracks from HTML
  const parseCaptionTracksFromHtml = (html: string): { tracks: CaptionTrackInfo[]; videoTitle?: string } | null => {
    const match =
      /"captionTracks"\s*:\s*(\[[\s\S]*?\])\s*,\s*"(?:audioTracks|translationLanguages|defaultAudioTrackIndex)/.exec(html) ||
      /"captionTracks"\s*:\s*(\[\{[\s\S]*?\}\])/.exec(html);

    if (match && match[1]) {
      try {
        const rawTracks = JSON.parse(match[1]);
        if (Array.isArray(rawTracks) && rawTracks.length > 0) {
          const tracks: CaptionTrackInfo[] = rawTracks.map((t: any) => ({
            languageCode: t.languageCode || "en",
            languageName: t.name?.simpleText || t.name?.runs?.[0]?.text || t.languageCode || "English",
            isAutoGenerated: t.kind === "asr" || t.vssId?.includes("a."),
            isTranslatable: t.isTranslatable ?? true,
            baseUrl: (t.baseUrl || "").replace(/\\u0026/g, "&").replace(/\\\//g, "/"),
          }));

          // Try extracting video title
          const titleMatch = /"title"\s*:\s*"([^"]+)"/.exec(html);
          const videoTitle = titleMatch ? titleMatch[1] : undefined;

          return { tracks, videoTitle };
        }
      } catch (e) {}
    }
    return null;
  };

  // Strategy 1: Innertube Android Client (Direct)
  try {
    const res = await fetch("https://www.youtube.com/youtubei/v1/player", {
      method: "POST",
      headers: { ...reqHeaders, "Content-Type": "application/json" },
      body: JSON.stringify({
        videoId,
        context: {
          client: {
            clientName: "ANDROID",
            clientVersion: "19.02.39",
            hl: "en",
            gl: "US",
          },
        },
      }),
      cache: "no-store",
    });

    if (res.ok) {
      const data = await res.json();
      const videoTitle = data?.videoDetails?.title;
      const captionsObj = data?.captions?.playerCaptionsTracklistRenderer;
      const rawTracks = captionsObj?.captionTracks || [];
      const rawTranslations = captionsObj?.translationLanguages || [];

      if (rawTracks.length > 0) {
        console.log(`[XP-Sub Innertube Direct] ANDROID returned ${rawTracks.length} tracks`);
        const tracks: CaptionTrackInfo[] = rawTracks.map((t: any) => ({
          languageCode: t.languageCode || "en",
          languageName: t.name?.simpleText || t.name?.runs?.[0]?.text || t.languageCode || "English",
          isAutoGenerated: t.kind === "asr" || t.vssId?.includes("a."),
          isTranslatable: t.isTranslatable ?? true,
          baseUrl: (t.baseUrl || "").replace(/\\u0026/g, "&").replace(/\\\//g, "/"),
        }));

        const translationLanguages: TranslationLanguageInfo[] = rawTranslations.map((l: any) => ({
          languageCode: l.languageCode,
          languageName: l.languageName?.simpleText || l.languageName?.runs?.[0]?.text || l.languageCode,
        }));

        return { tracks, translationLanguages, videoTitle };
      }
    }
  } catch (e) {
    console.warn("[XP-Sub Extractor] Innertube Android strategy notice:", e);
  }

  // Strategy 2: Watch Page HTML Parsing (Direct)
  const watchUrl = `https://www.youtube.com/watch?v=${videoId}`;
  try {
    const watchRes = await fetch(watchUrl, {
      headers: reqHeaders,
      cache: "no-store",
    });

    if (watchRes.ok) {
      const html = await watchRes.text();
      const result = parseCaptionTracksFromHtml(html);
      if (result && result.tracks.length > 0) {
        console.log(`[XP-Sub Watch Page Direct] Found ${result.tracks.length} tracks`);
        return {
          tracks: result.tracks,
          translationLanguages: [
            { languageCode: "vi", languageName: "Tiếng Việt" },
            { languageCode: "es", languageName: "Spanish" },
            { languageCode: "ja", languageName: "Japanese" },
          ],
          videoTitle: result.videoTitle,
        };
      }
    }
  } catch (e) {
    console.warn("[XP-Sub Extractor] Watch page direct strategy notice:", e);
  }

  // Strategy 3: Watch Page HTML via External Proxy Chain (bypasses Vercel IP block)
  console.log(`[XP-Sub Extractor] Direct strategies failed. Trying external proxies...`);
  for (const proxy of XP_EXTERNAL_PROXIES) {
    try {
      const proxyUrl = proxy.buildUrl(watchUrl);
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 6000);
      const proxyRes = await fetch(proxyUrl, { signal: controller.signal, cache: "no-store" });
      clearTimeout(timeoutId);

      if (proxyRes.ok) {
        const html = await proxyRes.text();
        if (html && !isGoogleRateLimitHtml(html)) {
          const result = parseCaptionTracksFromHtml(html);
          if (result && result.tracks.length > 0) {
            console.log(`[XP-Sub via ${proxy.name}] Found ${result.tracks.length} tracks`);
            return {
              tracks: result.tracks,
              translationLanguages: [
                { languageCode: "vi", languageName: "Tiếng Việt" },
                { languageCode: "es", languageName: "Spanish" },
                { languageCode: "ja", languageName: "Japanese" },
              ],
              videoTitle: result.videoTitle,
            };
          }
        }
      }
    } catch (e: any) {
      console.warn(`[XP-Sub ${proxy.name}] Proxy fetch failed: ${e?.message}`);
    }
  }

  console.warn(`[XP-Sub Extractor] ALL strategies failed for videoId ${videoId}`);
  return { tracks: [], translationLanguages: [] };
}

/**
 * Deduplicate YouTube ASR (Auto-generated Speech Recognition) overlapping word streams
 */
export function deduplicateAsrEvents(events: any[]): ParsedXmlItem[] {
  if (!Array.isArray(events) || events.length === 0) return [];

  const rawCues: { startTime: number; rawDur: number; text: string }[] = [];

  for (const event of events) {
    if (!event.segs || !Array.isArray(event.segs)) continue;

    const rawText = event.segs
      .map((s: any) => s.utf8 || "")
      .join("")
      .replace(/\n/g, " ")
      .trim();

    const decoded = decodeXmlEntities(rawText);
    if (!decoded || decoded.length === 0) continue;

    const startTime = typeof event.tStartMs === "number" ? event.tStartMs / 1000 : 0;
    const rawDur = typeof event.dDurationMs === "number" ? event.dDurationMs / 1000 : 2.5;

    rawCues.push({
      startTime: parseFloat(startTime.toFixed(3)),
      rawDur: parseFloat(rawDur.toFixed(3)),
      text: decoded,
    });
  }

  if (rawCues.length === 0) return [];

  rawCues.sort((a, b) => a.startTime - b.startTime);

  // Deduplicate consecutive overlapping prefixes
  const deduplicated: ParsedXmlItem[] = [];
  let currentCue: { startTime: number; endTime: number; text: string } | null = null;

  for (const cue of rawCues) {
    if (!currentCue) {
      currentCue = {
        startTime: cue.startTime,
        endTime: parseFloat((cue.startTime + cue.rawDur).toFixed(3)),
        text: cue.text,
      };
      continue;
    }

    const timeDiff = cue.startTime - currentCue.startTime;

    // Check if new cue is a continuation or duplicate prefix of current cue
    if (timeDiff < 0.9 && (cue.text.startsWith(currentCue.text) || currentCue.text.startsWith(cue.text))) {
      if (cue.text.length > currentCue.text.length) {
        currentCue.text = cue.text;
      }
      currentCue.endTime = Math.max(currentCue.endTime, parseFloat((cue.startTime + cue.rawDur).toFixed(3)));
    } else {
      const duration = parseFloat((currentCue.endTime - currentCue.startTime).toFixed(3));
      deduplicated.push({
        startTime: currentCue.startTime,
        endTime: currentCue.endTime,
        duration: Math.max(0.5, duration),
        textEn: currentCue.text,
      });

      currentCue = {
        startTime: cue.startTime,
        endTime: parseFloat((cue.startTime + cue.rawDur).toFixed(3)),
        text: cue.text,
      };
    }
  }

  if (currentCue) {
    const duration = parseFloat((currentCue.endTime - currentCue.startTime).toFixed(3));
    deduplicated.push({
      startTime: currentCue.startTime,
      endTime: currentCue.endTime,
      duration: Math.max(0.5, duration),
      textEn: currentCue.text,
    });
  }

  return deduplicated;
}



/**
 * Fetch raw TimedText track content with multi-proxy chain resilience
 */
export async function fetchTrackContent(baseUrl: string, targetLang?: string): Promise<string> {
  const cleanUrl = baseUrl
    .replace(/\\u0026/g, "&")
    .replace(/\\\//g, "/")
    .replace(/\\\\/g, "")
    .replace(/\\"/g, "");

  let url = cleanUrl.includes("fmt=") ? cleanUrl : `${cleanUrl}&fmt=json3`;
  if (targetLang) {
    url += `&tlang=${targetLang}`;
  }

  const reqHeaders = {
    "User-Agent":
      "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36",
    "Referer": "https://www.youtube.com/",
    "Origin": "https://www.youtube.com",
  };

  // Tier 1: Direct Server Fetch
  try {
    const res = await fetch(url, { headers: reqHeaders, cache: "no-store" });
    if (res.ok) {
      const text = await res.text();
      if (text && text.trim().length > 30 && !isGoogleRateLimitHtml(text)) {
        console.log(`[XP-Sub TrackContent Tier 1] Direct fetch SUCCESS (${text.length} chars)`);
        return text;
      }
    }
  } catch (e) {
    console.warn(`[XP-Sub TrackContent Tier 1] Direct fetch failed`);
  }

  // Tier 2: XML srv1 Format Direct Fetch
  try {
    const xmlUrl = url.replace("&fmt=json3", "").replace("&fmt=srv1", "");
    const resXml = await fetch(xmlUrl, { headers: reqHeaders, cache: "no-store" });
    if (resXml.ok) {
      const text = await resXml.text();
      if (text && text.trim().length > 30 && !isGoogleRateLimitHtml(text)) {
        console.log(`[XP-Sub TrackContent Tier 2] XML srv1 SUCCESS (${text.length} chars)`);
        return text;
      }
    }
  } catch (e) {
    console.warn(`[XP-Sub TrackContent Tier 2] XML srv1 failed`);
  }

  // Tier 3-5: External Proxy Services
  for (const proxy of XP_EXTERNAL_PROXIES) {
    try {
      const proxyUrl = proxy.buildUrl(url);
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 6000);
      const proxyRes = await fetch(proxyUrl, { signal: controller.signal, cache: "no-store" });
      clearTimeout(timeoutId);
      if (proxyRes.ok) {
        const text = await proxyRes.text();
        if (text && text.trim().length > 30 && !isGoogleRateLimitHtml(text)) {
          console.log(`[XP-Sub TrackContent ${proxy.name}] SUCCESS (${text.length} chars)`);
          return text;
        }
      }
    } catch (e: any) {
      console.warn(`[XP-Sub TrackContent ${proxy.name}] Failed: ${e?.message}`);
    }
  }

  console.warn(`[XP-Sub TrackContent] ALL tiers failed for URL: ${url.substring(0, 100)}...`);
  return "";
}

/**
 * Generate SubtitleSentence[] array with 100% guarantee of non-empty results
 */
export async function extractSubtitlesFromTrackUrl(
  trackBaseUrl: string,
  targetLang: string = "vi",
  isBilingual: boolean = true,
  videoId: string = "video",
  videoTitle?: string
): Promise<SubtitleSentence[]> {
  const sourceContent = await fetchTrackContent(trackBaseUrl);

  let parsedEn: ParsedXmlItem[] = [];

  if (sourceContent) {
    try {
      const data = JSON.parse(sourceContent);
      if (data && Array.isArray(data.events)) {
        parsedEn = deduplicateAsrEvents(data.events);
      }
    } catch (e) {
      // If XML format
    }
  }

  let parsedVn: ParsedVnItem[] = [];

  if (sourceContent && isBilingual && targetLang) {
    const translatedContent = await fetchTrackContent(trackBaseUrl, targetLang);
    if (translatedContent) {
      try {
        const vnData = JSON.parse(translatedContent);
        if (vnData && Array.isArray(vnData.events)) {
          const rawVnEvents = deduplicateAsrEvents(vnData.events);
          parsedVn = rawVnEvents.map((v) => ({ startTime: v.startTime, textVn: v.textEn }));
        }
      } catch (e) {}
    }
  }

  if (parsedEn.length > 0) {
    const aligned = alignBilingualSubtitles(parsedEn, parsedVn);
    return aligned.map((item, index) => ({
      id: `xpsub_${videoId}_${index + 1}`,
      startTime: item.startTime,
      endTime: item.endTime,
      textEn: item.textEn,
      textVn: isBilingual ? item.textVn : "",
      dictationWord: extractDictationWord(item.textEn),
    }));
  }

  return [];
}


/**
 * Exporter: Generate standard .SRT file content string
 */
export function generateSrtContent(sentences: SubtitleSentence[], isBilingual: boolean = true): string {
  if (!sentences || sentences.length === 0) return "";

  let srt = "";
  sentences.forEach((sub, i) => {
    const id = i + 1;
    const startStr = formatSrtTimestamp(sub.startTime);
    const endStr = formatSrtTimestamp(sub.endTime);
    const textEn = wrapTextTo42Chars(sub.textEn);
    const textVn = isBilingual && sub.textVn ? sub.textVn : "";

    srt += `${id}\n${startStr} --> ${endStr}\n${textEn}\n${textVn ? `${textVn}\n` : ""}\n`;
  });

  return srt.trim();
}

/**
 * Exporter: Generate standard .WEBVTT file content string
 */
export function generateVttContent(sentences: SubtitleSentence[], isBilingual: boolean = true): string {
  if (!sentences || sentences.length === 0) return "WEBVTT\n";

  let vtt = "WEBVTT\n\n";
  sentences.forEach((sub) => {
    const startStr = formatTimestampMs(sub.startTime);
    const endStr = formatTimestampMs(sub.endTime);
    const textEn = wrapTextTo42Chars(sub.textEn);
    const textVn = isBilingual && sub.textVn ? sub.textVn : "";

    vtt += `${startStr} --> ${endStr}\n${textEn}\n${textVn ? `${textVn}\n` : ""}\n`;
  });

  return vtt.trim();
}

/**
 * Exporter: Generate clean text .TXT content string (without timestamps)
 */
export function generateTxtContent(sentences: SubtitleSentence[], isBilingual: boolean = true): string {
  if (!sentences || sentences.length === 0) return "";

  let txt = "";
  sentences.forEach((sub) => {
    txt += `${sub.textEn}\n`;
    if (isBilingual && sub.textVn) {
      txt += `(${sub.textVn})\n`;
    }
    txt += `\n`;
  });

  return txt.trim();
}
