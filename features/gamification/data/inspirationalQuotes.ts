/**
 * Returns deterministic daily quote based on the day of the year
 */
export function getDailyInspirationalQuote(): InspirationalQuote {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const index = dayOfYear % INSPIRATIONAL_QUOTES.length;
  return INSPIRATIONAL_QUOTES[index];
}

/**
 * Returns a random quote different from the current one
 */
export function getRandomInspirationalQuote(currentId?: string): InspirationalQuote {
  const filtered = currentId
    ? INSPIRATIONAL_QUOTES.filter((q) => q.id !== currentId)
    : INSPIRATIONAL_QUOTES;
  const randomIndex = Math.floor(Math.random() * filtered.length);
  return filtered[randomIndex] || INSPIRATIONAL_QUOTES[0];
}
