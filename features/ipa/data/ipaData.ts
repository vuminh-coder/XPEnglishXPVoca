export type VowelLength = "short" | "long" | "dip";
export type VoicingType = "voiced" | "voiceless";

export interface IpaWordExample {
  word: string;
  phonetic: string;
  meaning: string;
  audioText?: string;
}

export interface IpaSound {
  id: string;
  symbol: string;
  name: string;
  category: IpaCategory;
  subCategory: "short_vowel" | "long_vowel" | "diphthong" | "voiced_consonant" | "voiceless_consonant";
  keyWord: string;
  keyWordPhonetic: string;
  vietnameseGuide: string;
  voicing: VoicingType;
  vowelLength?: VowelLength;
  
  // Articulation anatomy
  mouthShape: string;
  tonguePosition: string;
  jawOpening: string;
  airflowManner: string;
  
  // Tips for Vietnamese speakers
  commonMistakes: string;
  practiceTip: string;
  
  // Audio playback fallback phonetic text
  audioSampleText: string;
  
  // Examples
  examples: IpaWordExample[];
}

export interface MinimalPair {
  id: string;
  title: string;
  description: string;
  soundA: string;
  soundB: string;
  pairs: {
    wordA: string;
    phoneticA: string;
    meaningA: string;
    wordB: string;
    phoneticB: string;
    meaningB: string;
  }[];
}

