export interface DetailedBilingualSubtitleItem {
  id: number;
  start: string;
  end: string;
  duration: number;
  english: string;
  vietnamese: string;
  dictationWord: string;
  startSeconds: number;
  wordTimings?: WordTimingItem[];
}

export interface SubtitleExtractionResult {
  json: DetailedBilingualSubtitleItem[];
  srtBilingual: string;
  webvttBilingual: string;
  stats: {
    totalDurationStr: string;
    totalSubtitlesCount: number;
    totalEnglishSentences: number;
    totalEnglishWords: number;
    totalCharactersCount: number;
    translationSuccessRate: string;
    suspiciousSubtitlesCount: number;
    manualCheckRequiredCount: number;
  };
  errorReport: string[];
}

export interface RawSubtitleItem {
  startTime: number;
  endTime: number;
  duration?: number;
  textEn: string;
  textVn: string;
  dictationWord: string;
  wordTimings?: WordTimingItem[];
}

export interface ExtractedTrackInfo {
  lang: string;
  languageName?: string;
  kind?: string;
  baseUrl: string;
  isAutoGenerated?: boolean;
  isTranslatable?: boolean;
}

export interface SubtitleExtractionMetadata {
  videoId: string;
  title?: string;
  authorName?: string;
  durationSeconds?: number;
  tracks: ExtractedTrackInfo[];
  translationLanguages: { languageCode: string; languageName: string }[];
  selectedTrack?: ExtractedTrackInfo;
  failureReason?: string;
  sourceTier?: string;
  needClientFetch?: boolean;
}

export class SubtitleExtractionError extends Error {
  failureReason: string;
  metadata?: SubtitleExtractionMetadata;

  constructor(message: string, failureReason: string, metadata?: SubtitleExtractionMetadata) {
    super(message);
    this.name = "SubtitleExtractionError";
    this.failureReason = failureReason;
    this.metadata = metadata;
  }
}

const subtitleResultCache = new Map<string, {
  storeSubtitles: SubtitleSentence[];
  fullResult: SubtitleExtractionResult;
  metadata?: SubtitleExtractionMetadata;
}>();

let lastFetchedVideoMeta: SubtitleExtractionMetadata | null = null;

export function getLastFetchedVideoMeta(): SubtitleExtractionMetadata | null {
  return lastFetchedVideoMeta;
}

/**
 * Helper export for fetchYouTubeRealSubtitles
 */
export async function fetchYouTubeRealSubtitles(
  videoId: string,
  videoTitle: string,
  options?: { preferredLang?: string; forceRefresh?: boolean }
): Promise<SubtitleSentence[]> {
  const { storeSubtitles } = await processHighPrecisionSubtitles(videoId, videoTitle, options);
  return storeSubtitles;
}

/**
 * Builds structured `SubtitleSentence[]` and export payloads (`JSON`, `SRT`, `WEBVTT`) from raw cues.
 */
export function buildSubtitleArtifactsFromItems(
  videoId: string,
  rawSentences: RawSubtitleItem[]
): { storeSubtitles: SubtitleSentence[]; fullResult: SubtitleExtractionResult } {
  const jsonResult: DetailedBilingualSubtitleItem[] = [];
  let srtAcc = "";
  let vttAcc = "WEBVTT\n\n";
  let totalWordsCount = 0;
  let totalCharsCount = 0;
  let translatedCount = 0;
  const errorReport: string[] = [];

  rawSentences.forEach((item: RawSubtitleItem, index: number) => {
    const id = index + 1;
    const shiftedStart = shiftTimestampSec(item.startTime);
    const shiftedEnd = Math.max(shiftedStart + 0.3, shiftTimestampSec(item.endTime));
    const duration = parseFloat((shiftedEnd - shiftedStart).toFixed(3));
    const startMsStr = formatTimestampMs(shiftedStart);
    const endMsStr = formatTimestampMs(shiftedEnd);

    const cleanEn = item.textEn;
    const formattedEnForExport = wrapTextTo42Chars(cleanEn);
    const formattedVn = item.textVn || "";
    if (formattedVn.trim().length > 0) translatedCount++;

    totalWordsCount += cleanEn.split(/\s+/).filter(Boolean).length;
    totalCharsCount += cleanEn.length;

    jsonResult.push({
      id,
      start: startMsStr,
      end: endMsStr,
      duration,
      english: cleanEn,
      vietnamese: formattedVn,
      dictationWord: item.dictationWord || extractDictationWord(cleanEn),
      startSeconds: shiftedStart,
      wordTimings: item.wordTimings,
    });

    const vnExportLine = formattedVn ? `${formattedVn}\n` : "";
    srtAcc += `${id}\n${formatSrtTimestamp(shiftedStart)} --> ${formatSrtTimestamp(shiftedEnd)}\n${formattedEnForExport}\n${vnExportLine}\n`;
    vttAcc += `${startMsStr} --> ${endMsStr}\n${formattedEnForExport}\n${vnExportLine}\n`;
  });

  const lastEnd = rawSentences.length > 0 ? rawSentences[rawSentences.length - 1].endTime : 0;
  const translationRate =
    jsonResult.length > 0 ? `${Math.round((translatedCount / jsonResult.length) * 100)}%` : "0%";

  const fullResult: SubtitleExtractionResult = {
    json: jsonResult,
    srtBilingual: srtAcc.trim(),
    webvttBilingual: vttAcc.trim(),
    stats: {
      totalDurationStr: formatTimestampMs(lastEnd),
      totalSubtitlesCount: jsonResult.length,
      totalEnglishSentences: jsonResult.length,
      totalEnglishWords: totalWordsCount,
      totalCharactersCount: totalCharsCount,
      translationSuccessRate: translationRate,
      suspiciousSubtitlesCount: 0,
      manualCheckRequiredCount: jsonResult.length - translatedCount,
    },
    errorReport:
      errorReport.length > 0
        ? errorReport
        : ["Dữ liệu phụ đề đã được chuẩn hóa câu hoàn chỉnh và đồng bộ thời gian."],
  };

  const storeSubtitles: SubtitleSentence[] = jsonResult.map((j) => ({
    id: `yt_${videoId}_${j.id}`,
    startTime: j.startSeconds,
    endTime: parseFloat((j.startSeconds + j.duration).toFixed(3)),
    textEn: j.english,
    textVn: j.vietnamese,
    dictationWord: j.dictationWord,
    wordTimings: j.wordTimings,
  }));

  return { storeSubtitles, fullResult };
}

/**
 * High-Precision Multi-Format Subtitle Engine (JSON, SRT, WEBVTT).
 * Supports track language switching (`preferredLang`) and cache bypass (`forceRefresh`).
 */
export async function processHighPrecisionSubtitles(
  videoId: string,
  videoTitle?: string,
  options?: { preferredLang?: string; forceRefresh?: boolean }
): Promise<{
  storeSubtitles: SubtitleSentence[];
  fullResult: SubtitleExtractionResult;
  metadata?: SubtitleExtractionMetadata;
}> {
  void videoTitle;
  const cacheKey = `${videoId}:${options?.preferredLang || "default"}`;

  if (!options?.forceRefresh && subtitleResultCache.has(cacheKey)) {
    const hit = subtitleResultCache.get(cacheKey)!;
    if (hit.metadata) lastFetchedVideoMeta = hit.metadata;
    return hit;
  }

  const { rawSentences, metadata, errorMessage } = await fetchRawTimedTextData(videoId, options);
  if (metadata) {
    lastFetchedVideoMeta = metadata;
  }

  if (!rawSentences || rawSentences.length === 0) {
    throw new SubtitleExtractionError(
      errorMessage || "Video YouTube này không có phụ đề CC khả dụng.",
      metadata?.failureReason || "NO_CAPTIONS",
      metadata
    );
  }

  const artifacts = buildSubtitleArtifactsFromItems(videoId, rawSentences);
  const result = { ...artifacts, metadata };

  // Cache only non-empty successful results
  subtitleResultCache.set(cacheKey, result);
  return result;
}

/**
 * Fetches caption tracks or normalized subtitles from `/api/youtube/captions`,
 * falling back to our Same-Origin Proxy (`/api/youtube/subtitles/proxy`) when YouTube throttles server fetches.
 */
async function fetchRawTimedTextData(
  videoId: string,
  options?: { preferredLang?: string; forceRefresh?: boolean }
): Promise<{
  rawSentences: RawSubtitleItem[];
  metadata?: SubtitleExtractionMetadata;
  errorMessage?: string;
}> {
  const params = new URLSearchParams({ videoId });
  if (options?.preferredLang) params.set("lang", options.preferredLang);
  if (options?.forceRefresh) params.set("force", "1");

  let data: any = null;
  try {
    const apiRes = await fetch(`/api/youtube/captions?${params.toString()}`);
    data = await apiRes.json().catch(() => null);
  } catch (e) {
    console.warn("API route caption fetch warning:", e);
  }

  const metadata: SubtitleExtractionMetadata = {
    videoId,
    title: data?.title,
    authorName: data?.authorName,
    durationSeconds: data?.durationSeconds,
    tracks: Array.isArray(data?.tracks) ? data.tracks : [],
    translationLanguages: Array.isArray(data?.translationLanguages) ? data.translationLanguages : [],
    selectedTrack: data?.selectedTrack,
    failureReason: data?.failureReason,
    sourceTier: data?.sourceTier,
    needClientFetch: Boolean(data?.needClientFetch),
  };

  // Tier 1: Server returned parsed & normalized subtitles directly
  if (data?.success && Array.isArray(data.subtitles) && data.subtitles.length > 0) {
    return {
      rawSentences: data.subtitles.map((sub: any) => ({
        startTime: sub.startSeconds,
        endTime: parseFloat((sub.startSeconds + sub.duration).toFixed(3)),
        textEn: sub.english,
        textVn: sub.vietnamese ?? "",
        dictationWord: sub.dictationWord,
        wordTimings: sub.wordTimings,
      })),
      metadata,
    };
  }

  // Tier 2: Server discovered signed track URLs but IP download was throttled -> proxy fetch cleanly
  if (Array.isArray(data?.tracks) && data.tracks.length > 0) {
    const rawItems = await fetchTracksOnClient(data.tracks, options?.preferredLang);
    if (rawItems.length > 0) {
      return { rawSentences: rawItems, metadata: { ...metadata, failureReason: "OK" } };
    }
  }

  return {
    rawSentences: [],
    metadata,
    errorMessage:
      data?.error ||
      "Video YouTube này không có phụ đề khả dụng. Bạn có thể chọn track khác hoặc nhập file .srt / transcript.",
  };
}

const CLIENT_FALLBACK_PROXIES = [
  { name: "CorsProxy", type: "raw", buildUrl: (url: string) => `https://corsproxy.io/?${encodeURIComponent(url)}` },
  { name: "AllOriginsJSON", type: "json", buildUrl: (url: string) => `https://api.allorigins.win/get?url=${encodeURIComponent(url)}` },
];

function isValidTimedTextPayload(text: string): boolean {
  if (!text || text.trim().length < 25) return false;
  const lower = text.toLowerCase();
  if (
    lower.includes("we're sorry") ||
    lower.includes("<title>sorry...") ||
    lower.includes("automated queries") ||
    lower.includes("accounts.google.com/servicelogin") ||
    lower.includes("consent.youtube.com")
  ) {
    return false;
  }
  return text.includes('"events"') || text.includes("<text") || text.includes("<p ") || text.includes("-->");
}

/**
 * Fetches TimedText URLs prioritizing our Same-Origin SSRF-validated Proxy (`/api/youtube/subtitles/proxy`)
 * instead of violating CORS against youtube.com directly in the browser.
 */
async function clientFetchWithProxies(urls: string[]): Promise<string> {
  // Tier 0: Same-Origin Proxy (/api/youtube/subtitles/proxy) — never blocked by browser CORS
  for (const url of urls) {
    if (!isAllowedYouTubeTimedTextUrl(url)) continue;
    try {
      const res = await fetch(`/api/youtube/subtitles/proxy?url=${encodeURIComponent(url)}`, {
        signal: AbortSignal.timeout(6000),
      });
      if (res.ok) {
        const text = await res.text();
        if (isValidTimedTextPayload(text)) {
          return text;
        }
      }
    } catch {}
  }

  // Tier 1: Optional CORS proxy fallback when running in environments where serverless egress fails
  for (const proxy of CLIENT_FALLBACK_PROXIES) {
    for (const url of urls) {
      if (!isAllowedYouTubeTimedTextUrl(url)) continue;
      try {
        const res = await fetch(proxy.buildUrl(url), { signal: AbortSignal.timeout(4500) });
        if (res.ok) {
          let text = "";
          if (proxy.type === "json") {
            const data = await res.json();
            text = typeof data?.contents === "string" ? data.contents : "";
          } else {
            text = await res.text();
          }
          if (isValidTimedTextPayload(text)) {
            return text;
          }
        }
      } catch {}
    }
  }

  return "";
}

function buildTimedTextCandidateUrls(baseUrl: string, tlang?: string): string[] {
  try {
    const clean = baseUrl.replace(/\\u0026/g, "&").replace(/\\\//g, "/");
    const u1 = new URL(clean);
    u1.searchParams.set("fmt", "json3");
    if (tlang) u1.searchParams.set("tlang", tlang);

    const u2 = new URL(clean);
    u2.searchParams.set("fmt", "srv1");
    if (tlang) u2.searchParams.set("tlang", tlang);

    const u3 = new URL(clean);
    u3.searchParams.delete("fmt");
    if (tlang) u3.searchParams.set("tlang", tlang);

    return [u1.toString(), u2.toString(), u3.toString()];
  } catch {
    return [];
  }
}

async function fetchTracksOnClient(
  tracks: ExtractedTrackInfo[],
  preferredLang?: string
): Promise<RawSubtitleItem[]> {
  let primaryTrack = tracks[0];
  if (preferredLang) {
    const pref = tracks.find(
      (t) =>
        t.lang?.toLowerCase() === preferredLang.toLowerCase() ||
        t.lang?.toLowerCase().startsWith(preferredLang.toLowerCase() + "-")
    );
    if (pref) primaryTrack = pref;
  } else {
    const manualEn = tracks.find((t) => t.lang?.startsWith("en") && !t.isAutoGenerated && t.kind !== "asr");
    const anyEn = tracks.find((t) => t.lang?.startsWith("en"));
    primaryTrack = manualEn || anyEn || tracks[0];
  }

  if (!primaryTrack?.baseUrl) return [];

  const enUrls = buildTimedTextCandidateUrls(primaryTrack.baseUrl);
  const rawEn = await clientFetchWithProxies(enUrls);
  if (!rawEn) return [];

  const parsedEn = parseTimedTextAny(rawEn);
  if (parsedEn.length === 0) return [];

  const vnTrack = tracks.find((t) => t.lang?.toLowerCase().startsWith("vi"));
  const vnUrls = vnTrack
    ? buildTimedTextCandidateUrls(vnTrack.baseUrl)
    : primaryTrack.isTranslatable !== false
    ? buildTimedTextCandidateUrls(primaryTrack.baseUrl, "vi")
    : [];
  const rawVn = vnUrls.length > 0 ? await clientFetchWithProxies(vnUrls) : "";
  const parsedVn = rawVn ? parseVnTimedTextAny(rawVn) : [];

  const aligned = normalizeSubtitlePipeline(parsedEn as NormalizedCue[], parsedVn);
  const translated = await translateMissingVietnameseBatch(aligned);

  return translated.map((item) => ({
    startTime: item.startTime,
    endTime: item.endTime,
    textEn: item.textEn,
    textVn: item.textVn,
    dictationWord: extractDictationWord(item.textEn),
    wordTimings: item.wordTimings,
  }));
}
