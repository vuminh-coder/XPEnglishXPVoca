/**
 * XP-Sub Extractor Engine - Self-Contained In-House Subtitle Extraction & Downloader Engine
 * Delegates YouTube track discovery & TimedText fetch to the unified extractor,
 * normalizes sentences/timings with `subtitleNormalizer`, and exports `.srt`, `.vtt`, `.txt`.
 */

import { SubtitleSentence } from "@/stores/videoStore";
import {
  extractDictationWord,
  formatTimestampMs,
  formatSrtTimestamp,
  wrapTextTo42Chars,
  shiftTimestampSec,
  parseTimedTextAny,
  parseVnTimedTextAny,
  ParsedXmlItem,
  ParsedVnItem,
} from "@/features/listening/services/youtubeSubtitleParser";
import {
  normalizeSubtitlePipeline,
  NormalizedCue,
} from "@/features/listening/services/subtitleNormalizer";
import { translateMissingVietnameseBatch } from "@/features/listening/services/subtitleTranslateHelper";
import {
  discoverYouTubeTracks,
  fetchTrackContentOnServer,
  isGoogleBlockOrConsentHtml,
} from "@/features/listening/services/youtubeTrackExtractor";
import { refineUnpunctuatedAsrSubtitles } from "@/features/listening/services/aiSubtitleRefiner";

export interface CaptionTrackInfo {
  languageCode: string;
  languageName: string;
  isAutoGenerated: boolean;
  isTranslatable: boolean;
  baseUrl: string;
}

export interface TranslationLanguageInfo {
  languageCode: string;
  languageName: string;
}

export interface VideoTracksResult {
  success: boolean;
  videoId: string;
  videoTitle?: string;
  tracks: CaptionTrackInfo[];
  translationLanguages: TranslationLanguageInfo[];
}

/**
 * Check if payload is a Google Bot Throttling HTML page ("We're sorry...")
 */
export function isGoogleRateLimitHtml(text: string): boolean {
  return isGoogleBlockOrConsentHtml(text);
}

/**
 * Fetch all available caption tracks via unified YouTube Track Extractor (Innertube + Consent HTML + Worker)
 */
export async function fetchInnertubeCaptionTracks(videoId: string): Promise<{
  tracks: CaptionTrackInfo[];
  translationLanguages: TranslationLanguageInfo[];
  videoTitle?: string;
}> {
  const discovery = await discoverYouTubeTracks(videoId);
  return {
    tracks: discovery.tracks.map((t) => ({
      languageCode: t.lang,
      languageName: t.languageName,
      isAutoGenerated: t.isAutoGenerated,
      isTranslatable: t.isTranslatable,
      baseUrl: t.baseUrl,
    })),
    translationLanguages: discovery.translationLanguages,
    videoTitle: discovery.title,
  };
}

/**
 * Fetch raw TimedText track content using URL API across formats (json3 -> srv3 -> srv1 -> raw)
 */
export async function fetchTrackContent(baseUrl: string, targetLang?: string): Promise<string> {
  return fetchTrackContentOnServer(baseUrl, targetLang);
}

/**
 * Extract, normalize, and optionally translate subtitles from a chosen YouTube caption track URL.
 * Returns empty array if the upstream track payload could not be downloaded cleanly (never fabricates fake text).
 */
export async function extractSubtitlesFromTrackUrl(
  trackBaseUrl: string,
  targetLang: string = "vi",
  isBilingual: boolean = true,
  videoId: string = "video",
  videoTitle?: string
): Promise<SubtitleSentence[]> {
  void videoTitle;
  const sourceContent = await fetchTrackContent(trackBaseUrl);
  if (!sourceContent) return [];

  const parsedEn: ParsedXmlItem[] = parseTimedTextAny(sourceContent);
  if (parsedEn.length === 0) return [];

  let parsedVn: ParsedVnItem[] = [];
  if (isBilingual && targetLang) {
    const translatedContent = await fetchTrackContent(trackBaseUrl, targetLang);
    if (translatedContent) {
      parsedVn = parseVnTimedTextAny(translatedContent);
    }
  }

  let normalized = normalizeSubtitlePipeline(parsedEn as NormalizedCue[], parsedVn);
  const refined = await refineUnpunctuatedAsrSubtitles(normalized);
  if (refined !== normalized) {
    normalized = normalizeSubtitlePipeline(refined, parsedVn);
  }

  const finalItems =
    isBilingual && targetLang === "vi"
      ? await translateMissingVietnameseBatch(normalized)
      : normalized;

  return finalItems.map((item, index) => {
    const shiftedStart = shiftTimestampSec(item.startTime);
    const shiftedEnd = Math.max(shiftedStart + 0.3, shiftTimestampSec(item.endTime));
    return {
      id: `xpsub_${videoId}_${index + 1}`,
      startTime: shiftedStart,
      endTime: shiftedEnd,
      textEn: item.textEn,
      textVn: isBilingual ? item.textVn : "",
      dictationWord: extractDictationWord(item.textEn),
      wordTimings: item.wordTimings,
    };
  });
}

/**
 * Exporter: Generate standard .SRT file content string
 */
export function generateSrtContent(sentences: SubtitleSentence[], isBilingual: boolean = true): string {
  if (!sentences || sentences.length === 0) return "";

  let srt = "";
  sentences.forEach((sub, i) => {
    const id = i + 1;
    const startStr = formatSrtTimestamp(sub.startTime);
    const endStr = formatSrtTimestamp(sub.endTime);
    const textEn = wrapTextTo42Chars(sub.textEn);
    const textVn = isBilingual && sub.textVn ? sub.textVn : "";

    srt += `${id}\n${startStr} --> ${endStr}\n${textEn}\n${textVn ? `${textVn}\n` : ""}\n`;
  });

  return srt.trim();
}

/**
 * Exporter: Generate standard .WEBVTT file content string
 */
export function generateVttContent(sentences: SubtitleSentence[], isBilingual: boolean = true): string {
  if (!sentences || sentences.length === 0) return "WEBVTT\n";

  let vtt = "WEBVTT\n\n";
  sentences.forEach((sub) => {
    const startStr = formatTimestampMs(sub.startTime);
    const endStr = formatTimestampMs(sub.endTime);
    const textEn = wrapTextTo42Chars(sub.textEn);
    const textVn = isBilingual && sub.textVn ? sub.textVn : "";

    vtt += `${startStr} --> ${endStr}\n${textEn}\n${textVn ? `${textVn}\n` : ""}\n`;
  });

  return vtt.trim();
}

/**
 * Exporter: Generate clean text .TXT content string (without timestamps)
 */
export function generateTxtContent(sentences: SubtitleSentence[], isBilingual: boolean = true): string {
  if (!sentences || sentences.length === 0) return "";

  let txt = "";
  sentences.forEach((sub) => {
    txt += `${sub.textEn}\n`;
    if (isBilingual && sub.textVn) {
      txt += `(${sub.textVn})\n`;
    }
    txt += `\n`;
  });

  return txt.trim();
}
