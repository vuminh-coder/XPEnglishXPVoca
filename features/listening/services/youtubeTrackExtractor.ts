export function isGoogleBlockOrConsentHtml(text: string): boolean {
  if (!text) return true;
  const trimmed = text.trim();
  if (trimmed.length < 20) return true;
  const lower = trimmed.toLowerCase();
  const hasPlayerMeta =
    lower.includes('"captiontracks"') ||
    lower.includes('\\"captiontracks\\"') ||
    (lower.includes('"playabilitystatus"') && lower.includes('"videodetails"'));

  if (
    lower.includes("we're sorry") ||
    lower.includes("<title>sorry...") ||
    lower.includes("automated queries")
  ) {
    return true;
  }
  if (
    (lower.includes("accounts.google.com/servicelogin") ||
      lower.includes("consent.youtube.com")) &&
    !hasPlayerMeta
  ) {
    return true;
  }
  if (
    (lower.startsWith("<!doctype html") || lower.startsWith("<html")) &&
    !lower.includes("<text") &&
    !lower.includes("<p ") &&
    !lower.includes("captiontracks") &&
    !lower.includes('"events"')
  ) {
    return true;
  }
  return false;
}

function unescapeYouTubeUrl(rawUrl: string): string {
  return (rawUrl || "")
    .replace(/\\u0026/g, "&")
    .replace(/\\\//g, "/")
    .replace(/\\\\/g, "")
    .replace(/\\"/g, "")
    .trim();
}

/**
 * Balanced brace/bracket JSON extractor safe against semicolons/braces inside string literals.
 */
export function extractBalancedJsonAt(
  source: string,
  openIndex: number,
  openChar: "{" | "[",
  closeChar: "}" | "]"
): string | null {
  if (!source || openIndex < 0 || source[openIndex] !== openChar) return null;

  let depth = 0;
  let inString = false;
  let escaped = false;

  for (let i = openIndex; i < source.length; i++) {
    const ch = source[i];

    if (inString) {
      if (escaped) {
        escaped = false;
      } else if (ch === "\\") {
        escaped = true;
      } else if (ch === '"') {
        inString = false;
      }
      continue;
    }

    if (ch === '"') {
      inString = true;
    } else if (ch === openChar) {
      depth++;
    } else if (ch === closeChar) {
      depth--;
      if (depth === 0) {
        return source.slice(openIndex, i + 1);
      }
    }
  }

  return null;
}

function mapRawTracks(rawTracks: any[]): ExtractedTrackMeta[] {
  if (!Array.isArray(rawTracks)) return [];

  return rawTracks
    .map((t: any) => {
      const baseUrl = unescapeYouTubeUrl(t?.baseUrl || "");
      const lang = String(t?.languageCode || "en").trim() || "en";
      const kind = t?.kind === "asr" || String(t?.vssId || "").includes("a.") ? "asr" : "manual";
      const languageName =
        t?.name?.simpleText ||
        t?.name?.runs?.map((r: any) => r?.text || "").join("") ||
        lang;

      return {
        lang,
        languageName: String(languageName).trim() || lang,
        kind,
        baseUrl,
        vssId: typeof t?.vssId === "string" ? t.vssId : undefined,
        isAutoGenerated: kind === "asr",
        isTranslatable: t?.isTranslatable ?? true,
      };
    })
    .filter((t) => Boolean(t.baseUrl) && isAllowedYouTubeTimedTextUrl(t.baseUrl));
}

function mapTranslationLanguages(rawLangs: any[]): TranslationLanguageMeta[] {
  if (!Array.isArray(rawLangs) || rawLangs.length === 0) {
    return [
      { languageCode: "vi", languageName: "Tiếng Việt" },
      { languageCode: "en", languageName: "English" },
      { languageCode: "ja", languageName: "Japanese" },
      { languageCode: "ko", languageName: "Korean" },
      { languageCode: "zh-Hans", languageName: "Chinese (Simplified)" },
    ];
  }
  return rawLangs
    .map((l: any) => ({
      languageCode: String(l?.languageCode || ""),
      languageName: String(
        l?.languageName?.simpleText || l?.languageName?.runs?.[0]?.text || l?.languageCode || ""
      ),
    }))
    .filter((l) => Boolean(l.languageCode));
}

/**
 * Extracts captionTracks, player metadata, and playability status from YouTube Watch or Embed HTML.
 */
export function extractPlayerMetaFromHtml(html: string): {
  tracks: ExtractedTrackMeta[];
  translationLanguages: TranslationLanguageMeta[];
  title?: string;
  authorName?: string;
  durationSeconds?: number;
  playabilityStatus?: string;
} {
  if (!html) {
    return { tracks: [], translationLanguages: [] };
  }

  // Tier 1: Parse full ytInitialPlayerResponse cleanly via balanced brace scanner
  const markerRegex = /ytInitialPlayerResponse\s*=\s*\{/g;
  let m: RegExpExecArray | null;
  while ((m = markerRegex.exec(html)) !== null) {
    const braceStart = html.indexOf("{", m.index);
    const jsonStr = extractBalancedJsonAt(html, braceStart, "{", "}");
    if (jsonStr) {
      try {
        const player = JSON.parse(jsonStr);
        const renderer = player?.captions?.playerCaptionsTracklistRenderer;
        const tracks = mapRawTracks(renderer?.captionTracks || []);
        const translationLanguages = mapTranslationLanguages(renderer?.translationLanguages || []);
        const title = player?.videoDetails?.title;
        const authorName = player?.videoDetails?.author;
        const durationSeconds = player?.videoDetails?.lengthSeconds
          ? parseInt(player.videoDetails.lengthSeconds, 10)
          : undefined;
        const playabilityStatus = player?.playabilityStatus?.status;

        if (tracks.length > 0 || playabilityStatus || title) {
          return {
            tracks,
            translationLanguages,
            title,
            authorName,
            durationSeconds,
            playabilityStatus,
          };
        }
      } catch {}
    }
  }

  // Tier 2: Balanced extraction directly around "captionTracks":[...]
  const ctMatch = /"captionTracks"\s*:\s*\[/.exec(html);
  if (ctMatch) {
    const bracketStart = html.indexOf("[", ctMatch.index);
    const jsonArr = extractBalancedJsonAt(html, bracketStart, "[", "]");
    if (jsonArr) {
      try {
        const tracks = mapRawTracks(JSON.parse(jsonArr));
        if (tracks.length > 0) {
          const titleMatch = /"videoDetails"\s*:\s*\{[\s\S]{0,600}?"title"\s*:\s*"((?:[^"\\]|\\.)*)"/.exec(html);
          const authorMatch = /"author"\s*:\s*"((?:[^"\\]|\\.)*)"/.exec(html);
          return {
            tracks,
            translationLanguages: mapTranslationLanguages([]),
            title: titleMatch?.[1],
            authorName: authorMatch?.[1],
          };
        }
      } catch {}
    }
  }

  // Tier 3: TimedText baseUrl fallback supporting hyphenated BCP-47 lang codes (en-US, zh-Hans, pt-BR)
  const urlPattern = /https?:\\?\/\\?\/(?:www\.|m\.|music\.)?youtube\.com\\?\/api\\?\/timedtext[^"'\s\\<]*/g;
  const discoveredUrls: string[] = [];
  let urlMatch: RegExpExecArray | null;
  while ((urlMatch = urlPattern.exec(html)) !== null) {
    const clean = unescapeYouTubeUrl(urlMatch[0]);
    if (isAllowedYouTubeTimedTextUrl(clean) && !discoveredUrls.includes(clean)) {
      discoveredUrls.push(clean);
    }
  }

  if (discoveredUrls.length > 0) {
    const tracks: ExtractedTrackMeta[] = discoveredUrls.map((url, idx) => {
      const langMatch = /[?&]lang=([a-zA-Z0-9_-]+)/.exec(url);
      const kindMatch = /[?&]kind=([a-zA-Z0-9_-]+)/.exec(url);
      const lang = langMatch?.[1] || (idx === 0 ? "en" : "vi");
      const kind = kindMatch?.[1] === "asr" ? "asr" : "manual";
      return {
        lang,
        languageName: lang,
        kind,
        baseUrl: url,
        isAutoGenerated: kind === "asr",
        isTranslatable: true,
      };
    });
    return {
      tracks,
      translationLanguages: mapTranslationLanguages([]),
    };
  }

  return { tracks: [], translationLanguages: [] };
}

