function classifyPlayabilityFailure(status?: string): CaptionFailureReason {
  const upper = (status || "").toUpperCase();
  if (upper === "LOGIN_REQUIRED" || upper === "AGE_CHECK_REQUIRED") return "AGE_OR_LOGIN_REQUIRED";
  if (upper === "UNPLAYABLE" || upper === "ERROR") return "PRIVATE_OR_UNAVAILABLE";
  return "NO_CAPTIONS";
}

/**
 * Fetches track metadata via multi-client Innertube + Consent-cookie Watch/Embed HTML.
 */
export async function discoverYouTubeTracks(videoId: string): Promise<{
  tracks: ExtractedTrackMeta[];
  translationLanguages: TranslationLanguageMeta[];
  title: string;
  authorName: string;
  durationSeconds?: number;
  failureReason: CaptionFailureReason;
  sourceTier: string;
}> {
  let bestTitle = "";
  let bestAuthor = "";
  let bestDuration: number | undefined;
  let observedPlayability: string | undefined;

  // Step 0: Lightweight OEmbed metadata in parallel with Innertube Batch 1
  const oembedPromise = fetch(
    `https://www.youtube.com/oembed?url=https://www.youtube.com/watch?v=${videoId}&format=json`,
    { signal: AbortSignal.timeout(2500), cache: "no-store" }
  )
    .then(async (r) => (r.ok ? await r.json() : null))
    .catch(() => null);

  // Step 1: Parallel multi-client Innertube requests (fast 3.5s budget total)
  const innertubeResults = await Promise.allSettled(
    INNERTUBE_CLIENTS.map(async (client) => {
      const controller = new AbortController();
      const timeout = setTimeout(() => controller.abort(), 3800);
      try {
        const res = await fetch("https://www.youtube.com/youtubei/v1/player?prettyPrint=false", {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            "User-Agent": client.userAgent,
            "Accept-Language": "en-US,en;q=0.9",
          },
          body: JSON.stringify({
            videoId,
            contentCheckOk: true,
            racyCheckOk: true,
            context: {
              client: {
                clientName: client.clientName,
                clientVersion: client.clientVersion,
                hl: "en",
                gl: "US",
                ...(client.extraContext || {}),
              },
              ...(client.extraContext?.thirdParty ? { thirdParty: client.extraContext.thirdParty } : {}),
            },
          }),
          signal: controller.signal,
          cache: "no-store",
        });
        if (!res.ok) return null;
        const data = await res.json();
        return { client: client.name, data };
      } catch {
        return null;
      } finally {
        clearTimeout(timeout);
      }
    })
  );

  const oembed = await oembedPromise;
  if (oembed?.title) bestTitle = oembed.title;
  if (oembed?.author_name) bestAuthor = oembed.author_name;

  for (const res of innertubeResults) {
    if (res.status !== "fulfilled" || !res.value?.data) continue;
    const { client, data } = res.value;
    if (!bestTitle && data?.videoDetails?.title) bestTitle = data.videoDetails.title;
    if (!bestAuthor && data?.videoDetails?.author) bestAuthor = data.videoDetails.author;
    if (!bestDuration && data?.videoDetails?.lengthSeconds) {
      bestDuration = parseInt(data.videoDetails.lengthSeconds, 10) || undefined;
    }
    if (data?.playabilityStatus?.status && data.playabilityStatus.status !== "OK") {
      observedPlayability = data.playabilityStatus.status;
    }

    const renderer = data?.captions?.playerCaptionsTracklistRenderer;
    const tracks = mapRawTracks(renderer?.captionTracks || []);
    if (tracks.length > 0) {
      return {
        tracks,
        translationLanguages: mapTranslationLanguages(renderer?.translationLanguages || []),
        title: bestTitle || "Video Học Tiếng Anh YouTube",
        authorName: bestAuthor || "YouTube Creator",
        durationSeconds: bestDuration,
        failureReason: "OK",
        sourceTier: `Innertube:${client}`,
      };
    }
  }

  // Step 2: Parallel Watch Page + Embed HTML with Google Consent Bypass Cookies
  const htmlTargets = [
    {
      name: "WatchHtmlConsent",
      url: `https://www.youtube.com/watch?v=${videoId}&hl=en&bpctr=9999999999`,
    },
    {
      name: "EmbedHtml",
      url: `https://www.youtube.com/embed/${videoId}?hl=en`,
    },
  ];

  const htmlResults = await Promise.allSettled(
    htmlTargets.map(async (target) => {
      const controller = new AbortController();
      const timeout = setTimeout(() => controller.abort(), 4500);
      try {
        const res = await fetch(target.url, {
          headers: {
            ...DEFAULT_BROWSER_HEADERS,
            Accept: "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
            Cookie: CONSENT_COOKIE_HEADER,
            Referer: "https://www.youtube.com/",
          },
          signal: controller.signal,
          cache: "no-store",
        });
        if (!res.ok) return null;
        const html = await res.text();
        if (!html || isGoogleBlockOrConsentHtml(html)) {
          return { name: target.name, blocked: true as const };
        }
        return { name: target.name, blocked: false as const, meta: extractPlayerMetaFromHtml(html) };
      } catch {
        return null;
      } finally {
        clearTimeout(timeout);
      }
    })
  );

  let anyBlocked = false;
  for (const res of htmlResults) {
    if (res.status !== "fulfilled" || !res.value) continue;
    if (res.value.blocked) {
      anyBlocked = true;
      continue;
    }
    const { meta, name } = res.value;
    if (!bestTitle && meta.title) bestTitle = meta.title;
    if (!bestAuthor && meta.authorName) bestAuthor = meta.authorName;
    if (!bestDuration && meta.durationSeconds) bestDuration = meta.durationSeconds;
    if (meta.playabilityStatus && meta.playabilityStatus !== "OK") {
      observedPlayability = meta.playabilityStatus;
    }
    if (meta.tracks.length > 0) {
      return {
        tracks: meta.tracks,
        translationLanguages: meta.translationLanguages,
        title: bestTitle || "Video Học Tiếng Anh YouTube",
        authorName: bestAuthor || "YouTube Creator",
        durationSeconds: bestDuration,
        failureReason: "OK",
        sourceTier: name,
      };
    }
  }

  // Step 3: Optional configured external worker (e.g., dedicated Residential/yt-dlp endpoint)
  const workerEndpoint = process.env.YOUTUBE_CAPTION_WORKER_URL?.trim();
  if (workerEndpoint) {
    try {
      const workerUrl = new URL(workerEndpoint);
      workerUrl.searchParams.set("videoId", videoId);
      const res = await fetch(workerUrl.toString(), {
        signal: AbortSignal.timeout(5000),
        cache: "no-store",
      });
      if (res.ok) {
        const wData = await res.json();
        const wTracks = mapRawTracks(wData?.tracks || []);
        if (wTracks.length > 0) {
          return {
            tracks: wTracks,
            translationLanguages: mapTranslationLanguages(wData?.translationLanguages || []),
            title: wData?.title || bestTitle || "Video Học Tiếng Anh YouTube",
            authorName: wData?.authorName || bestAuthor || "YouTube Creator",
            durationSeconds: bestDuration,
            failureReason: "OK",
            sourceTier: "ExternalWorker",
          };
        }
      }
    } catch {}
  }

  const failureReason: CaptionFailureReason = observedPlayability
    ? classifyPlayabilityFailure(observedPlayability)
    : anyBlocked
    ? "BOT_BLOCKED"
    : "NO_CAPTIONS";

  return {
    tracks: [],
    translationLanguages: [],
    title: bestTitle || "Video Học Tiếng Anh YouTube",
    authorName: bestAuthor || "YouTube Creator",
    durationSeconds: bestDuration,
    failureReason,
    sourceTier: "None",
  };
}

function isValidTrackPayload(text: string, fmt?: string): boolean {
  if (!text || isGoogleBlockOrConsentHtml(text)) return false;
  const trimmed = text.trim();
  if (fmt === "json3") {
    try {
      const parsed = JSON.parse(trimmed);
      return Array.isArray(parsed?.events) && parsed.events.length > 0;
    } catch {
      return false;
    }
  }
  return (
    trimmed.includes("<text") ||
    trimmed.includes("<p ") ||
    trimmed.includes("-->") ||
    trimmed.includes('"events"')
  );
}

/**
 * Fetches raw TimedText track content using URL API across formats (json3 -> srv3 -> srv1 -> raw).
 */
async function fetchTrackContentDetailed(
  baseUrl: string,
  targetLang?: string
): Promise<{ content: string; rateLimited: boolean }> {
  const cleanUrl = unescapeYouTubeUrl(baseUrl);
  if (!isAllowedYouTubeTimedTextUrl(cleanUrl)) {
    return { content: "", rateLimited: false };
  }

  const candidateFormats: (string | null)[] = ["json3", "srv3", "srv1", null];

  for (const fmt of candidateFormats) {
    try {
      const urlObj = new URL(cleanUrl);
      if (fmt) {
        urlObj.searchParams.set("fmt", fmt);
      } else {
        urlObj.searchParams.delete("fmt");
      }

      if (targetLang && /^[a-zA-Z0-9_-]{2,15}$/.test(targetLang)) {
        urlObj.searchParams.set("tlang", targetLang);
      }

      const controller = new AbortController();
      const timeout = setTimeout(() => controller.abort(), 3500);
      try {
        const res = await fetch(urlObj.toString(), {
          headers: {
            ...DEFAULT_BROWSER_HEADERS,
            Referer: "https://www.youtube.com/",
            Origin: "https://www.youtube.com",
          },
          signal: controller.signal,
          cache: "no-store",
        });

        if (res.status === 429 || res.status === 403) {
          return { content: "", rateLimited: true };
        }

        if (res.ok) {
          const text = await res.text();
          if (isGoogleBlockOrConsentHtml(text)) {
            return { content: "", rateLimited: true };
          }
          if (isValidTrackPayload(text, fmt || undefined)) {
            return { content: text, rateLimited: false };
          }
        }
      } finally {
        clearTimeout(timeout);
      }
    } catch {}
  }

  return { content: "", rateLimited: false };
}

export async function fetchTrackContentOnServer(
  baseUrl: string,
  targetLang?: string
): Promise<string> {
  const res = await fetchTrackContentDetailed(baseUrl, targetLang);
  return res.content;
}

function isEnglishTrack(track: ExtractedTrackMeta): boolean {
  const code = track.lang.toLowerCase();
  const vss = (track.vssId || "").toLowerCase();
  return code === "en" || code.startsWith("en-") || code.startsWith("en_") || vss.includes(".en");
}

function isPredominantlyLatinEnglish(cues: ParsedXmlItem[]): boolean {
  if (!Array.isArray(cues) || cues.length === 0) return false;
  let latinChars = 0;
  let foreignScriptChars = 0;
  for (const cue of cues) {
    const clean = cue.textEn || "";
    const latin = clean.match(/[A-Za-z]/g);
    latinChars += latin ? latin.length : 0;
    const foreign = clean.match(
      /[\u0400-\u04FF\u0600-\u06FF\u0E00-\u0E7F\u1100-\u11FF\u3040-\u30FF\u3130-\u318F\u4E00-\u9FFF\uAC00-\uD7AF]/g
    );
    foreignScriptChars += foreign ? foreign.length : 0;
  }
  const total = latinChars + foreignScriptChars;
  if (total === 0) return false;
  return latinChars / total >= 0.7;
}

/**
 * Selects preferred caption track (honors explicit preferredLang if present, else Manual EN -> ASR EN -> Any translatable track capped at 2).
 */
function pickCandidateTracks(tracks: ExtractedTrackMeta[], preferredLang?: string) {
  if (preferredLang) {
    const prefLower = preferredLang.toLowerCase();
    const exactPref = tracks.find(
      (t) => t.lang.toLowerCase() === prefLower || t.lang.toLowerCase().startsWith(prefLower + "-")
    );
    if (exactPref) {
      return {
        primary: exactPref,
        backups: tracks.filter((t) => t !== exactPref && isEnglishTrack(t)),
        manualEn: isEnglishTrack(exactPref) && !exactPref.isAutoGenerated ? exactPref : undefined,
        asrEn: isEnglishTrack(exactPref) && exactPref.isAutoGenerated ? exactPref : undefined,
        hasAnyEnglishTrack: tracks.some(isEnglishTrack),
      };
    }
  }

  const enTracks = tracks.filter(isEnglishTrack);
  const manualEn = enTracks.find((t) => !t.isAutoGenerated);
  const asrEn = enTracks.find((t) => t.isAutoGenerated);
  const otherEn = enTracks.find((t) => t !== manualEn && t !== asrEn);

  // Never iterate dozens of non-English tracks (ar, bn, hy...) when English exists; only try <= 2 translatable tracks if zero EN exists
  const translatableNonEn =
    enTracks.length === 0 ? tracks.filter((t) => t.isTranslatable).slice(0, 2) : [];

  const ordered = [manualEn, asrEn, otherEn, ...enTracks, ...translatableNonEn].filter(
    (t, idx, arr): t is ExtractedTrackMeta => Boolean(t) && arr.indexOf(t) === idx
  );

  return {
    primary: ordered[0],
    backups: ordered.slice(1),
    manualEn,
    asrEn,
    hasAnyEnglishTrack: enTracks.length > 0,
  };
}

/**
 * Full server-side YouTube caption extraction & multi-tier normalization pipeline.
 */
export async function extractYouTubeCaptionsOnServer(
  inputUrlOrId: string,
  options?: {
    preferredLang?: string;
    includeAiPunctuation?: boolean;
    includeVietnamese?: boolean;
  }
): Promise<ServerExtractionResult> {
  const videoId = extractYouTubeVideoId(inputUrlOrId);
  if (!videoId) {
    return {
      success: false,
      videoId: "",
      title: "",
      authorName: "",
      tracks: [],
      translationLanguages: [],
      subtitles: [],
      needClientFetch: false,
      hasCaptions: false,
      isAiGenerated: false,
      failureReason: "INVALID_VIDEO_ID",
    };
  }

  const includeAiPunctuation = options?.includeAiPunctuation ?? true;
  const includeVietnamese = options?.includeVietnamese ?? true;

  const discovery = await discoverYouTubeTracks(videoId);
  let hitRateLimit = false;

  if (discovery.tracks.length > 0) {
    const { primary, backups, manualEn, asrEn, hasAnyEnglishTrack } = pickCandidateTracks(
      discovery.tracks,
      options?.preferredLang
    );

    let bestParsedEn: ParsedXmlItem[] = [];
    let chosenTrack: ExtractedTrackMeta | undefined = primary;

    if (primary) {
      const needsEnTranslate =
        !isEnglishTrack(primary) && !options?.preferredLang && primary.isTranslatable;
      const primaryRes = await fetchTrackContentDetailed(
        primary.baseUrl,
        needsEnTranslate ? "en" : undefined
      );
      if (primaryRes.rateLimited) {
        hitRateLimit = true;
      } else if (primaryRes.content) {
        const parsed = parseTimedTextAny(primaryRes.content);
        if (options?.preferredLang || isEnglishTrack(primary) || isPredominantlyLatinEnglish(parsed)) {
          bestParsedEn = parsed;
        }
      }

      // Guard against incomplete/stub manual captions when full ASR exists
      if (
        !hitRateLimit &&
        !options?.preferredLang &&
        manualEn &&
        primary === manualEn &&
        asrEn &&
        bestParsedEn.length < 15
      ) {
        const asrRes = await fetchTrackContentDetailed(asrEn.baseUrl);
        if (asrRes.rateLimited) {
          hitRateLimit = true;
        } else if (asrRes.content) {
          const parsedAsr = parseTimedTextAny(asrRes.content);
          if (parsedAsr.length > Math.max(bestParsedEn.length * 2.5, 10)) {
            bestParsedEn = parsedAsr;
            chosenTrack = asrEn;
          }
        }
      }
    }

    if (bestParsedEn.length === 0 && !hitRateLimit) {
      for (const backup of backups) {
        const needsEnTranslate =
          !isEnglishTrack(backup) && !options?.preferredLang && backup.isTranslatable;
        const backupRes = await fetchTrackContentDetailed(
          backup.baseUrl,
          needsEnTranslate ? "en" : undefined
        );
        if (backupRes.rateLimited) {
          hitRateLimit = true;
          break;
        }
        if (backupRes.content) {
          const parsed = parseTimedTextAny(backupRes.content);
          if (
            parsed.length > 0 &&
            (options?.preferredLang || isEnglishTrack(backup) || isPredominantlyLatinEnglish(parsed))
          ) {
            bestParsedEn = parsed;
            chosenTrack = backup;
            break;
          }
        }
      }
    }

    if (bestParsedEn.length > 0 && chosenTrack) {
      let parsedVn: { startTime: number; endTime?: number; textVn: string }[] = [];
      if (includeVietnamese) {
        const vnTrack = discovery.tracks.find((t) => /^vi(-|$)/i.test(t.lang));
        if (vnTrack) {
          const vnRes = await fetchTrackContentDetailed(vnTrack.baseUrl);
          if (vnRes.content) {
            parsedVn = parseVnTimedTextAny(vnRes.content);
          }
        }
      }

      let aligned = normalizeSubtitlePipeline(bestParsedEn as NormalizedCue[], parsedVn);

      if (includeAiPunctuation) {
        const refinedEn = await refineUnpunctuatedAsrSubtitles(aligned);
        if (refinedEn !== aligned) {
          aligned = normalizeSubtitlePipeline(refinedEn, parsedVn);
        }
      }

      const withVn = includeVietnamese
        ? await translateMissingVietnameseBatch(aligned)
        : aligned;

      const subtitles: NormalizedCaptionLine[] = withVn.map((item, idx) => ({
        id: idx + 1,
        start: formatTimestampMs(item.startTime),
        end: formatTimestampMs(item.endTime),
        duration: item.duration,
        english: item.textEn,
        vietnamese: item.textVn,
        dictationWord: extractDictationWord(item.textEn),
        startSeconds: item.startTime,
        wordTimings: item.wordTimings,
      }));

      return {
        success: true,
        videoId,
        title: discovery.title,
        authorName: discovery.authorName,
        durationSeconds: discovery.durationSeconds,
        tracks: discovery.tracks,
        translationLanguages: discovery.translationLanguages,
        selectedTrack: chosenTrack,
        subtitles,
        needClientFetch: false,
        hasCaptions: subtitles.length > 0,
        isAiGenerated: false,
        failureReason: "OK",
        sourceTier: discovery.sourceTier,
      };
    }

    // Track metadata discovered cleanly, but server IP timedtext download was throttled -> Client handoff (only if English or explicitly requested lang exists)
    if (options?.preferredLang || hasAnyEnglishTrack) {
      return {
        success: true,
        videoId,
        title: discovery.title,
        authorName: discovery.authorName,
        durationSeconds: discovery.durationSeconds,
        tracks: discovery.tracks,
        translationLanguages: discovery.translationLanguages,
        selectedTrack: primary,
        subtitles: [],
        needClientFetch: true,
        hasCaptions: true,
        isAiGenerated: false,
        failureReason: "NEED_CLIENT_FETCH",
        sourceTier: discovery.sourceTier,
      };
    }

    return {
      success: false,
      videoId,
      title: discovery.title,
      authorName: discovery.authorName,
      durationSeconds: discovery.durationSeconds,
      tracks: discovery.tracks,
      translationLanguages: discovery.translationLanguages,
      subtitles: [],
      needClientFetch: false,
      hasCaptions: false,
      isAiGenerated: false,
      failureReason: "NO_CAPTIONS",
      sourceTier: discovery.sourceTier,
    };
  }

  // Fallback Tier: LRCLIB synced lyrics strictly for available music videos without captions (never for unavailable/blocked or placeholder titles)
  if (
    discovery.failureReason === "NO_CAPTIONS" &&
    discovery.title &&
    discovery.title !== "Video Học Tiếng Anh YouTube"
  ) {
    try {
      const lrcItems = await fetchLrclibSyncedLyrics(
        discovery.title,
        discovery.authorName,
        videoId,
        discovery.durationSeconds
      );
      if (lrcItems && lrcItems.length > 0) {
        const rawEn: NormalizedCue[] = lrcItems.map((it) => ({
          startTime: it.startTime,
          endTime: it.endTime,
          duration: Math.max(0.4, parseFloat((it.endTime - it.startTime).toFixed(3))),
          textEn: it.textEn,
        }));
        const aligned = normalizeSubtitlePipeline(rawEn, []);
        const withVn = includeVietnamese ? await translateMissingVietnameseBatch(aligned) : aligned;
        const subtitles: NormalizedCaptionLine[] = withVn.map((item, idx) => ({
          id: idx + 1,
          start: formatTimestampMs(item.startTime),
          end: formatTimestampMs(item.endTime),
          duration: item.duration,
          english: item.textEn,
          vietnamese: item.textVn,
          dictationWord: extractDictationWord(item.textEn),
          startSeconds: item.startTime,
        }));

        return {
          success: true,
          videoId,
          title: discovery.title,
          authorName: discovery.authorName,
          durationSeconds: discovery.durationSeconds,
          tracks: [],
          translationLanguages: [],
          subtitles,
          needClientFetch: false,
          hasCaptions: true,
          isAiGenerated: false,
          failureReason: "OK",
          sourceTier: "LRCLIB",
        };
      }
    } catch {}
  }

  return {
    success: false,
    videoId,
    title: discovery.title,
    authorName: discovery.authorName,
    durationSeconds: discovery.durationSeconds,
    tracks: [],
    translationLanguages: discovery.translationLanguages,
    subtitles: [],
    needClientFetch: false,
    hasCaptions: false,
    isAiGenerated: false,
    failureReason: discovery.failureReason,
    sourceTier: discovery.sourceTier,
  };
}
